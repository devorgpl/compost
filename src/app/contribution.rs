//! Collects what links add to the user's compose services and renders the
//! compose override file (spec §10.8). Shared by every kind.

use std::collections::{BTreeMap, BTreeSet};

use anyhow::{Result, bail};
use serde_yaml_ng::{Mapping, Value};

use crate::config::app::ComposeFile;

#[derive(Debug, Default)]
pub struct Contribution {
    services: BTreeMap<String, ServiceChanges>,
    external_networks: BTreeSet<String>,
}

#[derive(Debug, Default)]
struct ServiceChanges {
    /// Network name → aliases on that network.
    networks: BTreeMap<String, Vec<String>>,
    environment: BTreeMap<String, String>,
}

impl Contribution {
    /// Attach a compose service to an external network, optionally with an alias.
    pub fn join_network(&mut self, service: &str, network: &str, alias: Option<String>) {
        self.external_networks.insert(network.to_string());
        let aliases = self
            .service(service)
            .networks
            .entry(network.to_string())
            .or_default();
        if let Some(alias) = alias {
            if !aliases.contains(&alias) {
                aliases.push(alias);
            }
        }
    }

    /// Set an environment variable; setting it twice to different values is an error.
    pub fn set_env(&mut self, service: &str, key: &str, value: String) -> Result<()> {
        let environment = &mut self.service(service).environment;
        match environment.get(key) {
            Some(existing) if *existing != value => {
                bail!("variable {key} of service `{service}` is set twice with different values")
            }
            _ => {
                environment.insert(key.to_string(), value);
                Ok(())
            }
        }
    }

    fn service(&mut self, service: &str) -> &mut ServiceChanges {
        self.services.entry(service.to_string()).or_default()
    }

    /// The compose override file. It contains secrets, so store it as 0600.
    pub fn override_yaml(&self, compose: &ComposeFile) -> Result<String> {
        let mut services = Mapping::new();
        for (name, changes) in &self.services {
            let original = compose.services.get(name);
            let mut service = Mapping::new();

            if !changes.networks.is_empty() {
                if let Some(mode) = original.and_then(|s| s.network_mode.as_deref()) {
                    bail!("service `{name}` uses `network_mode: {mode}` and cannot join depap networks");
                }
                let mut networks = Mapping::new();
                // Listing networks replaces the implicit default network, so
                // keep it unless the service chose its own networks.
                if !original.is_some_and(|s| s.has_networks) {
                    networks.insert("default".into(), Value::Mapping(Mapping::new()));
                }
                for (network, aliases) in &changes.networks {
                    let mut settings = Mapping::new();
                    if !aliases.is_empty() {
                        let aliases = aliases.iter().map(|a| Value::from(a.as_str())).collect();
                        settings.insert("aliases".into(), Value::Sequence(aliases));
                    }
                    networks.insert(network.as_str().into(), Value::Mapping(settings));
                }
                service.insert("networks".into(), Value::Mapping(networks));
            }

            if !changes.environment.is_empty() {
                let environment = changes
                    .environment
                    .iter()
                    // Compose treats `$` as variable interpolation; `$$` is a literal `$`.
                    .map(|(k, v)| (Value::from(k.as_str()), Value::from(v.replace('$', "$$"))))
                    .collect();
                service.insert("environment".into(), Value::Mapping(environment));
            }
            services.insert(name.as_str().into(), Value::Mapping(service));
        }

        let mut networks = Mapping::new();
        for network in &self.external_networks {
            let mut external = Mapping::new();
            external.insert("external".into(), true.into());
            networks.insert(network.as_str().into(), Value::Mapping(external));
        }

        let mut root = Mapping::new();
        root.insert("services".into(), Value::Mapping(services));
        if !networks.is_empty() {
            root.insert("networks".into(), Value::Mapping(networks));
        }
        let yaml = serde_yaml_ng::to_string(&root)?;
        Ok(format!("# Generated by depap. Do not edit; run `depap app deploy`.\n{yaml}"))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn compose() -> ComposeFile {
        ComposeFile::parse(
            "services: {web: {image: x}, api: {image: x, networks: [internal]}, host: {image: x, network_mode: host}}",
        )
        .unwrap()
    }

    #[test]
    fn renders_networks_aliases_and_environment() {
        let mut c = Contribution::default();
        c.join_network("web", "depap-ingress", Some("app-main-web".into()));
        c.join_network("api", "depap-db-pg", None);
        c.set_env("api", "PASSWORD", "a$b".into()).unwrap();

        let yaml = c.override_yaml(&compose()).unwrap();
        let value: Value = serde_yaml_ng::from_str(&yaml).unwrap();
        let expected: Value = serde_yaml_ng::from_str(
            "
services:
  api:
    networks: {depap-db-pg: {}}
    environment: {PASSWORD: a$$b}
  web:
    networks: {default: {}, depap-ingress: {aliases: [app-main-web]}}
networks:
  depap-db-pg: {external: true}
  depap-ingress: {external: true}
",
        )
        .unwrap();
        assert_eq!(value, expected);
    }

    #[test]
    fn conflicting_environment_is_an_error() {
        let mut c = Contribution::default();
        c.set_env("api", "X", "1".into()).unwrap();
        c.set_env("api", "X", "1".into()).unwrap();
        assert!(c.set_env("api", "X", "2".into()).is_err());
    }

    #[test]
    fn network_mode_services_cannot_join_networks() {
        let mut c = Contribution::default();
        c.join_network("host", "depap-ingress", None);
        assert!(c.override_yaml(&compose()).is_err());
    }
}
