#!/bin/sh
# User documentation in docs/wiki (published to the Gitea wiki by
# scripts/publish-wiki.sh).
#
#   scripts/docs.sh           # regenerate CLI-Reference.md from `compost … --help`
#   scripts/docs.sh --check   # fail if CLI-Reference.md is out of date or a
#                             # link between pages is broken (`just ci`)
#
# CLI-Reference.md documents options once, in the clap doc comments of src/cli.
set -eu

pages=docs/wiki
out=$pages/CLI-Reference.md
check=false
[ "${1:-}" = --check ] && check=true

cargo build --quiet
bin=target/debug/compost
# Help shows the current value of variables it reads, so they must be unset.
unset COMPOST_SERVER COMPOST_HOME

# commands ARGS...: the subcommands listed under "Commands:" in the help of ARGS.
commands() {
    "$bin" "$@" --help | awk '
        /^Commands:/ { on = 1; next }
        on && /^$/ { exit }
        on && /^  [a-z]/ && $1 != "help" { print $1 }'
}

# section ARGS...: the help of the command, then of each subcommand.
section() {
    printf '\n## `compost%s`\n\n```text\n' "$(printf ' %s' "$@")"
    "$bin" "$@" --help
    printf '```\n'
    for sub in $(commands "$@"); do
        section "$@" "$sub"
    done
}

generated="$(mktemp)"
trap 'rm -f "$generated"' EXIT
{
    printf '# CLI reference\n\n'
    printf '<!-- Generated by scripts/docs.sh from the help texts in src/cli; run `just docs` instead of editing. -->\n\n'
    printf 'The `--help` of every command. Guides: [Applications](Applications.md), [Servers and shared apps](Servers-and-Shared-Apps.md), [Backup and restore](Backup-and-Restore.md).\n\n'
    printf 'Exit codes: `0` OK · `1` unexpected error · `2` invalid local config or usage · `3` server not ready or a server-side check failed · `4` deployed, but not healthy · `130` interrupted with Ctrl-C.\n\n'
    printf '## `compost`\n\n```text\n'
    "$bin" --help
    printf '```\n'
    for sub in $(commands); do
        section "$sub"
    done
} >"$generated"

if ! $check; then
    cp "$generated" "$out"
    echo "Wrote $out"
    exit 0
fi

failed=false
if ! diff -u "$out" "$generated"; then
    echo "$out is out of date: run \`just docs\`" >&2
    failed=true
fi

# anchors PAGE: the anchors of its headings, as Gitea and GitHub make them:
# lowercase, punctuation dropped, spaces to `-`. Code blocks are skipped.
anchors() {
    awk '/^```/ { code = !code; next } !code && /^#+ / { sub(/^#+ /, ""); print }' "$1" |
        tr 'A-Z' 'a-z' | sed -e 's/[^a-z0-9 _-]//g' -e 's/ /-/g'
}

# Links to pages (`Page.md`, `Page.md#part`) and within a page (`#part`).
for page in "$pages"/*.md; do
    grep -o '](\([A-Za-z0-9_-]*\.md\)\{0,1\}\(#[^)]*\)\{0,1\})' "$page" | sed 's/^](\(.*\))$/\1/' |
        while read -r link; do
            target="${link%%#*}"
            anchor=""
            case "$link" in *'#'*) anchor="${link#*#}" ;; esac
            [ -n "$target" ] || target="$(basename "$page")"
            if [ ! -f "$pages/$target" ]; then
                echo "$page: link to missing page $link" >&2
                echo x
            elif [ -n "$anchor" ] && ! anchors "$pages/$target" | grep -qx -- "$anchor"; then
                echo "$page: link to missing heading $link" >&2
                echo x
            fi
        done
done | grep -q x && failed=true

if $failed; then
    exit 1
fi
echo "$pages is up to date"
